// # Detailed Technical Documentation

// ## Component Details

// ### 1. **Hardware Layer (Motorola E7 Power)**
// - **Processor**: MediaTek Helio G25 (8-core ARM Cortex-A53)
// - **RAM**: 4GB (System uses ~1.5GB, leaving 2.3GB available)
// - **Storage**: 64GB (44GB free after OS and apps)
// - **Battery**: 5000mAh (must stay plugged in for server use)
// - **Temperature**: Runs at 33-55°C under load

// ### 2. **Android OS Layer**
// - Base operating system
// - Manages hardware resources
// - Provides isolated app environments
// - Handles power management

// ### 3. **Termux (Terminal Environment)**
// - **What it is**: Full Linux environment on Android
// - **SSH Server**: Allows remote access (port 8022)
// - **Package Manager**: Install Linux tools with `pkg install`
// - **Purpose**: Bridge between Android and Linux software

// ### 4. **Proot-Distro (Ubuntu Container)**
// - **What it is**: Runs full Ubuntu inside Termux
// - **Why needed**: Ollama requires full Linux environment
// - **Architecture**: ARM64 compatible
// - **Isolation**: Separate from Android, uses same kernel

// ### 5. **Ollama Server**
// - **Version**: 0.14.2
// - **Port**: 11434 (localhost only, not exposed directly)
// - **API**: RESTful HTTP API for model interaction
// - **Models Storage**: ~/.ollama/models
// - **Memory Management**: Loads models on-demand, unloads when idle

// ### 6. **Qwen2.5-Coder Model**
// - **Parameters**: 1.5 billion
// - **Size on Disk**: ~1GB
// - **RAM Usage**: 1.5-2GB when loaded
// - **Specialization**: Code generation, debugging, explanations
// - **Performance**: 1-3 tokens/second on your hardware

// ### 7. **Cloudflare Tunnel (cloudflared)**
// - **Purpose**: Expose local server to internet securely
// - **How it works**: Persistent encrypted connection to Cloudflare
// - **Benefits**: 
//   - No port forwarding
//   - No dynamic DNS needed
//   - Free HTTPS certificate
//   - DDoS protection
//   - Works behind NAT/firewall

